"""Step 5: writes the package read by the mobile app (contract: packages/shared/src/artwork-package.ts)."""

import base64
import json
from pathlib import Path

import numpy as np
from PIL import Image
from scipy import ndimage

DISPLAY_IMAGE_SIDE = 1600
HIGHLIGHT_FILL = (255, 214, 10, 70)
HIGHLIGHT_OUTLINE = (255, 214, 10, 255)
PREVIEW_COLORS = [(230, 25, 75), (60, 180, 75), (0, 130, 200), (255, 225, 25), (240, 50, 230), (70, 240, 240)]


def encode_layer(layer: np.ndarray) -> str:
    return base64.b64encode(layer.astype(np.uint8).tobytes()).decode()


def highlight_image(mask: np.ndarray) -> Image.Image:
    """Translucent fill with a solid outline, laid over the artwork while the object is touched."""
    outline = mask & ~ndimage.binary_erosion(mask, iterations=3)
    pixels = np.zeros((*mask.shape, 4), dtype=np.uint8)
    pixels[mask] = HIGHLIGHT_FILL
    pixels[outline] = HIGHLIGHT_OUTLINE
    return Image.fromarray(pixels, "RGBA")


def write_package(
    out_dir: Path,
    source: dict,
    described: dict,
    image: Image.Image,
    object_ids: np.ndarray,
    depth: np.ndarray,
    edges: np.ndarray,
) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    for stale in out_dir.glob("highlight-*.png"):
        stale.unlink()

    height, width = object_ids.shape
    manifest = {
        "id": source["id"],
        "title": source["title"],
        "author": source["author"],
        "year": source["year"],
        "institution": source["institution"],
        "license": source["license"],
        "source": source["source"],
        "description": described["description"],
        "layers": {"width": width, "height": height},
        "objects": [
            {
                "id": index + 1,
                "label": item["label"],
                "shortDescription": item["shortDescription"],
                "longDescription": item["longDescription"],
                "sound": item["sound"],
            }
            for index, item in enumerate(described["objects"])
        ],
    }
    (out_dir / "manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n")

    layers = {"objectIds": encode_layer(object_ids), "depth": encode_layer(depth), "edges": encode_layer(edges)}
    (out_dir / "layers.json").write_text(json.dumps(layers) + "\n")

    display = image.copy()
    display.thumbnail((DISPLAY_IMAGE_SIDE, DISPLAY_IMAGE_SIDE))
    display.save(out_dir / "image.jpg", quality=85)

    for item in manifest["objects"]:
        highlight_image(object_ids == item["id"]).save(out_dir / f"highlight-{item['id']}.png", optimize=True)


def write_preview(path: Path, image: Image.Image, object_ids: np.ndarray, depth: np.ndarray) -> None:
    """Masks over the artwork next to the depth map, for the curator to check the result."""
    height, width = object_ids.shape
    colors = np.array([(0, 0, 0)] + [PREVIEW_COLORS[i % len(PREVIEW_COLORS)] for i in range(255)])
    tinted = np.asarray(image.resize((width, height))) * 0.45 + colors[object_ids] * 0.55
    tinted[object_ids == 0] = np.asarray(image.resize((width, height)))[object_ids == 0]
    depth_rgb = np.repeat(depth[:, :, None], 3, axis=2)
    Image.fromarray(np.hstack([tinted.astype(np.uint8), depth_rgb])).save(path, quality=85)


def write_registry(artworks_dir: Path, registry_file: Path) -> None:
    """Metro only bundles assets named in a literal require(), so the list of packages is generated."""
    entries = []
    for manifest_file in sorted(artworks_dir.glob("*/manifest.json")):
        manifest = json.loads(manifest_file.read_text())
        base = f"../../assets/artworks/{manifest['id']}"
        highlights = "".join(
            f"      {item['id']}: require('{base}/highlight-{item['id']}.png'),\n" for item in manifest["objects"]
        )
        entries.append(
            "  {\n"
            f"    manifest: require('{base}/manifest.json'),\n"
            f"    image: require('{base}/image.jpg'),\n"
            f"    loadLayers: () => require('{base}/layers.json'),\n"
            f"    highlights: {{\n{highlights}    }},\n"
            "  },\n"
        )
    registry_file.parent.mkdir(parents=True, exist_ok=True)
    registry_file.write_text(
        "// Generated by pipeline/build.py - do not edit by hand.\n"
        "import type { ArtworkEntry } from './artwork';\n\n"
        f"export const ARTWORKS: ArtworkEntry[] = [\n{''.join(entries)}];\n"
    )
